"""Agent state schemas and Gemini structured output contracts.

Implements TRD.md §M, PLAN.md T-SCHEMA-04, and Phase 6 structured output contracts.
Explicitly distinguishes LLM-generated outputs from deterministic fallback via provenance metadata.
"""

from datetime import datetime, timezone
from typing import Any
from uuid import UUID, uuid4
from pydantic import BaseModel, Field

from risk_manager.domain.schemas.enums import (
    Action,
    AgentFallbackReason,
    AgentName,
    AgentProvider,
    AgentRunStatus,
    EvidenceQuality,
    VerifierRecommendation,
)


class InvestigationResult(BaseModel):
    """Structured output contract for Investigator agent (TRD.md §M & Phase 6)."""

    case_id: UUID = Field(default_factory=uuid4, description="Correlation / risk decision ID")
    agent_name: AgentName = Field(default=AgentName.INVESTIGATOR)
    status: AgentRunStatus = Field(default=AgentRunStatus.COMPLETED)

    # Provenance tracking (Issue 2)
    provider: str = Field(
        default=AgentProvider.DETERMINISTIC_FALLBACK.value,
        description="GEMINI or DETERMINISTIC_FALLBACK",
    )
    is_llm_generated: bool = Field(
        default=False,
        description="True if generated by real Gemini LLM, False if deterministic fallback",
    )
    fallback_reason: str | None = Field(
        default=None,
        description="Explicit reason when fallback occurs, None when Gemini succeeds",
    )
    model_name: str | None = Field(
        default=None,
        description="Model name/version if generated by Gemini LLM",
    )

    # Phase 6 rich structured fields
    evidence_summary: str = Field(
        default="", description="Executive synthesis of behavioral and transactional facts"
    )
    key_risk_factors: list[str] = Field(
        default_factory=list, description="Dominant signals indicating return abuse or risk"
    )
    mitigating_factors: list[str] = Field(
        default_factory=list, description="Protective signals indicating legitimate customer behavior"
    )
    evidence_quality: EvidenceQuality = Field(
        default=EvidenceQuality.MEDIUM, description="Assessment of evidence completeness and strength"
    )
    missing_information: list[str] = Field(
        default_factory=list, description="Missing features, history, or telemetry"
    )
    contradictions: list[str] = Field(
        default_factory=list, description="Contradictions within customer data or order facts"
    )
    confidence: float = Field(default=0.85, ge=0.0, le=1.0, description="Agent confidence score")
    recommendation: str = Field(
        default="PROCEED", description="Investigator operational recommendation (PROCEED/ESCALATE)"
    )
    prompt_injection_detected: bool = Field(
        default=False, description="Flag indicating adversarial prompt injection attempt detected"
    )
    source_decision_id: UUID | None = Field(
        default=None, description="Reference to original immutable risk decision"
    )

    # Backward compatibility with Phase 2 TRD.md §M
    evidence: list[str] = Field(
        default_factory=list, description="Synthesized behavioral facts list"
    )
    anomalies: list[str] = Field(
        default_factory=list, description="Unusual transactional or timing patterns"
    )
    investigator_confidence: float = Field(
        default=0.85, ge=0.0, le=1.0, description="Confidence alias for backward compatibility"
    )


