class AgentWorkflowResult(BaseModel):
    """Final aggregated result of the asynchronous LangGraph multi-agent workflow."""

    decision_id: UUID
    risk_decision_id: UUID
    policy_decision_id: UUID
    p_return_abuse: float = Field(ge=0.0, le=1.0, description="Immutable numerical score from Phase 4")
    risk_band: str
    selected_action: Action = Field(description="Immutable selected action from Phase 5")
    expected_loss: float = Field(default=0.0, description="Authoritative expected loss from Phase 5")
    expected_net_value: float = Field(default=0.0, description="Authoritative expected net value from Phase 5")

    # Provenance tracking (Issue 2)
    provider: str = Field(
        default=AgentProvider.DETERMINISTIC_FALLBACK.value,
        description="GEMINI or DETERMINISTIC_FALLBACK",
    )
    is_llm_generated: bool = Field(
        default=False,
        description="True if generated by real Gemini LLM, False if deterministic fallback",
    )
    fallback_reason: str | None = Field(
        default=None,
        description="Explicit reason when fallback occurs, None when Gemini succeeds",
    )
    model_name: str | None = Field(
        default=None,
        description="Configured or used model name",
    )

    investigator_result: InvestigationResult | None = None
    verifier_result: VerificationResult | None = None
    orchestrator_result: ActionDecision | None = None
    requires_human_review: bool = False
    disagreements: list[str] = Field(default_factory=list)
    final_agent_recommendation: str = "CONFIRM"
    agent_status: AgentRunStatus = AgentRunStatus.COMPLETED
    agent_errors: list[str] = Field(default_factory=list)
    latency_ms: float = 0.0
    trace_id: str = Field(default_factory=lambda: str(uuid4()))
    created_at: datetime = Field(default_factory=lambda: datetime.now(timezone.utc))
