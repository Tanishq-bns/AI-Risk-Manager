    """Structured output contract for Action Orchestrator agent (TRD.md §M & Phase 6)."""

    agent_name: AgentName = Field(default=AgentName.ACTION_ORCHESTRATOR)
    status: AgentRunStatus = Field(default=AgentRunStatus.COMPLETED)

    # Provenance tracking (Issue 2)
    provider: str = Field(
        default=AgentProvider.DETERMINISTIC_FALLBACK.value,
        description="GEMINI or DETERMINISTIC_FALLBACK",
    )
    is_llm_generated: bool = Field(
        default=False,
        description="True if generated by real Gemini LLM, False if deterministic fallback",
    )
    fallback_reason: str | None = Field(
        default=None,
        description="Explicit reason when fallback occurs, None when Gemini succeeds",
    )
    model_name: str | None = Field(
        default=None,
        description="Model name/version if generated by Gemini LLM",
    )

    # Phase 6 operational recommendation fields
    selected_action_reference: Action = Field(
        default=Action.A0, description="Immutable reference to the Phase 5 selected action"
    )
    execution_mode: str = Field(
        default="AUTOMATED",
        description="AUTOMATED (direct pipeline), MANUAL_REVIEW_QUEUE (route to human), ESCALATED",
    )
    operational_recommendation: str = Field(
        default="CONFIRM", description="Operational execution guidance for fulfillment"
    )
    requires_human_review: bool = Field(
        default=False, description="True if operational review required before intervention"
    )
    blockers: list[str] = Field(
        default_factory=list, description="Operational blockers preventing immediate execution"
    )
    confidence: float = Field(
        default=0.95, ge=0.0, le=1.0, description="Orchestrator confidence"
    )

    # Backward compatibility with Phase 2 TRD.md §M
    action: Action = Field(
        default=Action.A0, description="Selected action alias"
    )
    rationale: str = Field(
        default="", description="Operational rationale explanation"
    )
    expected_net_value: float = Field(
        default=0.0, description="Preserved economic expected net value"
    )
    policy_constraints_satisfied: bool = Field(
        default=True, description="Whether guardrails were validated"
    )
    requires_manual_review: bool = Field(
        default=False, description="Alias for requires_human_review"
    )


